"""构建器：JDK/SDK 检测、签名 keystore 生成、Gradle 构建与 APK 校验。"""
import os
import re
import subprocess

DEFAULT_PW = "sanjiu-release"


def _jdk_candidates(hint):
    cands = []
    if hint:
        cands.append(hint)
    if os.environ.get("JAVA_HOME"):
        cands.append(os.environ["JAVA_HOME"])
    if os.environ.get("JDK_HOME"):
        cands.append(os.environ["JDK_HOME"])
    return cands


def find_jdk(hint=None):
    for c in _jdk_candidates(hint):
        if c and os.path.isdir(c):
            for b in ("java", "java.exe"):
                if os.path.exists(os.path.join(c, "bin", b)):
                    return c
    return None


def java_major(jdk):
    try:
        out = subprocess.run([os.path.join(jdk, "bin", "java"), "-version"],
                             capture_output=True, text=True).stderr
        m = re.search(r'version "(\d+)', out)
        return int(m.group(1)) if m else None
    except Exception:
        return None


def find_sdk(hint=None):
    cands = [hint, os.environ.get("ANDROID_HOME"), os.environ.get("ANDROID_SDK_ROOT"),
             os.path.expanduser("~/Android/Sdk")]
    for c in cands:
        if c and os.path.isdir(c) and os.path.isdir(os.path.join(c, "cmdline-tools")):
            return c
    return None


def write_local_properties(proj, sdk):
    with open(os.path.join(proj, "local.properties"), "w") as f:
        f.write("## auto-generated by sanjiu-apk-builder\n")
        f.write(f"sdk.dir={sdk}\n")


def ensure_keystore(proj, jdk):
    ks_dir = os.path.join(proj, "keystore")
    os.makedirs(ks_dir, exist_ok=True)
    ks = os.path.join(ks_dir, "release.jks")
    if not os.path.exists(ks):
        keytool = os.path.join(jdk, "bin", "keytool")
        subprocess.run([keytool, "-genkeypair", "-keystore", ks, "-alias", "release",
                        "-storepass", DEFAULT_PW, "-keypass", DEFAULT_PW,
                        "-keyalg", "RSA", "-keysize", "2048", "-validity", "10000",
                        "-dname", "CN=Sanjiu, OU=Dev, O=Sanjiu, L=City, ST=State, C=CN"],
                       check=True, capture_output=True)
    with open(os.path.join(proj, "gradle.properties"), "w") as f:
        f.write("# auto-generated by sanjiu-apk-builder\n")
        f.write(f"RELEASE_STORE_FILE={ks}\n")
        f.write(f"RELEASE_STORE_PASSWORD={DEFAULT_PW}\n")
        f.write("RELEASE_KEY_ALIAS=release\n")
        f.write(f"RELEASE_KEY_PASSWORD={DEFAULT_PW}\n")
    return ks


def _apksigner(sdk):
    bt = os.path.join(sdk, "build-tools")
    if os.path.isdir(bt):
        vers = sorted(v for v in os.listdir(bt)
                      if os.path.exists(os.path.join(bt, v, "apksigner")))
        if vers:
            return os.path.join(bt, vers[-1], "apksigner")
    return None


def build(proj, jdk_hint=None, sdk_hint=None):
    proj = os.path.abspath(proj)
    jdk = find_jdk(jdk_hint)
    if not jdk or java_major(jdk) != 17:
        raise SystemExit(
            "需要 JDK 17（AGP 8.9 要求）。请用 --jdk 指定 JDK17 路径，或设置 JAVA_HOME。")
    sdk = find_sdk(sdk_hint)
    if not sdk:
        raise SystemExit(
            "需要 Android SDK。请用 --sdk 指定 SDK 路径，或设置 ANDROID_HOME。")
    write_local_properties(proj, sdk)
    ensure_keystore(proj, jdk)

    env = dict(os.environ, JAVA_HOME=jdk, ANDROID_HOME=sdk)
    env["PATH"] = os.path.join(jdk, "bin") + os.pathsep + env["PATH"]
    gradlew = os.path.join(proj, "gradlew")
    os.chmod(gradlew, 0o755)
    print("== Gradle assembleRelease ==")
    r = subprocess.run([gradlew, "assembleRelease", "--no-daemon", "--console=plain"],
                       env=env, cwd=proj, capture_output=True, text=True)
    print(r.stdout[-2500:])
    if r.returncode != 0:
        print(r.stderr[-1500:])
        raise SystemExit("构建失败，见上方日志")

    apk = os.path.join(proj, "app/build/outputs/apk/release/app-release.apk")
    if not os.path.exists(apk):
        raise SystemExit("构建完成但未找到 APK 产物")
    apksigner = _apksigner(sdk)
    if apksigner:
        v = subprocess.run([apksigner, "verify", apk], capture_output=True, text=True)
        print("apksigner verify:", "OK（签名有效）" if v.returncode == 0
              else ("WARN " + v.stderr[-300:]))
    print("APK:", apk, f"({os.path.getsize(apk)} B)")
    return apk
